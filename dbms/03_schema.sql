-- MoodBeats Database Schema
-- PostgreSQL
-- Seven normalized tables

-- 1. USER
CREATE TABLE users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_name VARCHAR(100) NOT NULL
);

-- 2. STUDY_GOAL
-- Each user has one current weekly study goal.
CREATE TABLE study_goal (
    user_id BIGINT PRIMARY KEY,
    weekly_goal_minutes INTEGER NOT NULL
        CHECK (weekly_goal_minutes > 0),

    CONSTRAINT fk_study_goal_user
        FOREIGN KEY (user_id)
        REFERENCES users(user_id)
        ON DELETE CASCADE
);

-- 3. AUDIO_TYPE
CREATE TABLE audio_type (
    audio_id VARCHAR(20) PRIMARY KEY,
    audio_name VARCHAR(50) NOT NULL UNIQUE,
    audio_type VARCHAR(20) NOT NULL
        CHECK (audio_type IN ('synthetic', 'none'))
);

-- Initial audio environments used by MoodBeats.
INSERT INTO audio_type (audio_id, audio_name, audio_type)
VALUES
    ('lofi', 'Lo-fi', 'synthetic'),
    ('instr', 'Instrumental', 'synthetic'),
    ('nature', 'Nature', 'synthetic'),
    ('freq', 'Frequency', 'synthetic'),
    ('ambient', 'Ambient', 'synthetic'),
    ('none', 'Silence', 'none');

-- 4. STUDY_TASK
CREATE TABLE study_task (
    task_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_name VARCHAR(150) NOT NULL UNIQUE
);

-- Standard study tasks available in the application.
INSERT INTO study_task (task_name)
VALUES
    ('Reading'),
    ('Writing'),
    ('Problem solving'),
    ('Memorizing'),
    ('Revision'),
    ('Coding');

-- Custom tasks can be inserted into this table as separate records.

-- 5. STUDY_SESSION
CREATE TABLE study_session (
    session_id BIGINT PRIMARY KEY,
    user_id BIGINT NOT NULL,
    task_id BIGINT NOT NULL,
    audio_id VARCHAR(20) NOT NULL,
    session_timestamp TIMESTAMPTZ NOT NULL,
    actual_minutes INTEGER NOT NULL
        CHECK (actual_minutes >= 0),
    target_minutes INTEGER NOT NULL
        CHECK (target_minutes BETWEEN 1 AND 180),
    completion_type VARCHAR(10) NOT NULL
        CHECK (completion_type IN ('TIMER', 'EARLY')),

    CONSTRAINT fk_session_user
        FOREIGN KEY (user_id)
        REFERENCES users(user_id),

    CONSTRAINT fk_session_task
        FOREIGN KEY (task_id)
        REFERENCES study_task(task_id),

    CONSTRAINT fk_session_audio
        FOREIGN KEY (audio_id)
        REFERENCES audio_type(audio_id)
);

-- 6. PRE_CHECK_IN
CREATE TABLE pre_check_in (
    session_id BIGINT PRIMARY KEY,
    mood SMALLINT NOT NULL
        CHECK (mood BETWEEN 1 AND 5),
    stress SMALLINT NOT NULL
        CHECK (stress BETWEEN 1 AND 10),
    focus SMALLINT NOT NULL
        CHECK (focus BETWEEN 1 AND 10),

    CONSTRAINT fk_pre_check_in_session
        FOREIGN KEY (session_id)
        REFERENCES study_session(session_id)
        ON DELETE CASCADE
);

-- 7. POST_CHECK_IN
CREATE TABLE post_check_in (
    session_id BIGINT PRIMARY KEY,
    mood SMALLINT NOT NULL
        CHECK (mood BETWEEN 1 AND 5),
    stress SMALLINT NOT NULL
        CHECK (stress BETWEEN 1 AND 10),
    focus SMALLINT NOT NULL
        CHECK (focus BETWEEN 1 AND 10),
    task_completion VARCHAR(20) NOT NULL
        CHECK (
            task_completion IN (
                'completed',
                'partial',
                'not_completed'
            )
        ),
    notes TEXT,

    CONSTRAINT fk_post_check_in_session
        FOREIGN KEY (session_id)
        REFERENCES study_session(session_id)
        ON DELETE CASCADE
);

-- Indexes for common session lookups.
CREATE INDEX idx_study_session_user_timestamp
    ON study_session(user_id, session_timestamp);

CREATE INDEX idx_study_session_task
    ON study_session(task_id);

CREATE INDEX idx_study_session_audio
    ON study_session(audio_id);
